def main():
    VALIDATION_DIR.mkdir(parents=True, exist_ok=True)
    VALIDATION_CACHE_DIR.mkdir(parents=True, exist_ok=True)

    demo.create_scene()
    outward_domain, _ = configure_validation_domain(
        "Outward Smoke Domain",
        "outward_smoke",
        max(VALIDATION_FRAMES),
    )
    trail_domain, _ = configure_validation_domain(
        "Rocket Trail Domain",
        "rocket_trail",
        max(VALIDATION_FRAMES),
    )

    outward_ok = bake_domain(outward_domain, "outward_smoke")
    trail_ok = bake_domain(trail_domain, "rocket_trail")

    bpy.ops.wm.save_as_mainfile(filepath=str(VALIDATION_BLEND_PATH))
    print(f"SAVED_VALIDATION_BLEND {VALIDATION_BLEND_PATH}")

    for frame in VALIDATION_FRAMES:
        render_validation_frame(frame)

    write_report(outward_ok, trail_ok)


if __name__ == "__main__":
    main()
