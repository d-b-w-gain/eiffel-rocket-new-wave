"""
Bake validation caches and render Eiffel rocket comparison stills.

Run from the project root with:
& "C:\\Program Files (x86)\\Steam\\steamapps\\common\\Blender\\blender.exe" --background --python scripts\\validate_bakes.py

This script is intentionally for validation, not final output. The main scene
keeps tutorial-resolution simulation settings; this uses smaller caches so the
end-to-end bake/render path can be checked quickly.
"""

from pathlib import Path
import os
import sys

import bpy

SCRIPT_DIR = Path(__file__).resolve().parent
if str(SCRIPT_DIR) not in sys.path:
    sys.path.insert(0, str(SCRIPT_DIR))

import rocket_launch_demo as demo


VALIDATION_DIR = demo.RENDERS_DIR / "validation"
VALIDATION_CACHE_DIR = demo.CACHE_DIR / "validation"
VALIDATION_BLEND_PATH = VALIDATION_DIR / "eiffel_rocket_validation.blend"
VALIDATION_FRAMES = (40, 80, 120, 160, 200)
VALIDATION_RESOLUTION = int(os.environ.get("BLENDER_ROCKET_VALIDATION_RESOLUTION", "64"))
VALIDATION_RENDER_RESOLUTION = (1280, 720)


def configure_validation_domain(domain_name, cache_name, frame_end):
    domain = bpy.data.objects[domain_name]
    settings = domain.modifiers[domain_name].domain_settings
    settings.resolution_max = VALIDATION_RESOLUTION
    settings.cache_directory = str(VALIDATION_CACHE_DIR / cache_name)
    settings.cache_type = "MODULAR"
    settings.cache_resumable = True
    settings.cache_frame_start = demo.FRAME_START
    settings.cache_frame_end = frame_end
    return domain, settings


def bake_domain(domain, label):
    bpy.ops.object.select_all(action="DESELECT")
    domain.select_set(True)
    bpy.context.view_layer.objects.active = domain
    print(f"BAKE_START {label}")
    bpy.ops.fluid.bake_data()
    settings = domain.modifiers[domain.name].domain_settings
    print(f"BAKE_DONE {label} data={settings.has_cache_baked_data}")
    return settings.has_cache_baked_data


def render_validation_frame(frame):
    scene = bpy.context.scene
    scene.frame_set(frame)
    scene.cycles.samples = 32
    scene.cycles.use_denoising = True
    scene.render.resolution_x = VALIDATION_RENDER_RESOLUTION[0]
    scene.render.resolution_y = VALIDATION_RENDER_RESOLUTION[1]
    scene.render.filepath = str(VALIDATION_DIR / f"frame_{frame:03d}.png")
    bpy.ops.render.render(write_still=True)
    print(f"RENDERED frame={frame} path={scene.render.filepath}")


